-- ============================================================================
-- JEEVAN-NET — patient record storage
-- ============================================================================
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Safe to re-run: every statement is guarded (if not exists / drop + create).
--
-- WHY THIS FILE EXISTS
-- The live project diverged from supabase/schema.sql:
--   * public.profiles was created WITHOUT abha_id, so the app's profile write
--     fails on a fresh sign-up and only shows up as a console warning.
--   * public.assessments exists (id, user_id, created_at, vitals, symptoms,
--     triage_result) but had no policies, so RLS rejects every insert.
-- This file reconciles both and is the only thing you need to paste.
--
-- WHAT RLS DOES HERE
-- With RLS enabled and no policy, a request is silently rejected. Each policy
-- below scopes a row to its owner via auth.uid(), so one patient can never read
-- or write another patient's record. The anon key ships in the browser, so these
-- policies — not the key — are what protect the data.
-- ============================================================================

-- ---------------------------------------------------------------- profiles --
alter table public.profiles add column if not exists abha_id text;

alter table public.profiles enable row level security;

drop policy if exists "profiles: read own" on public.profiles;
create policy "profiles: read own"
  on public.profiles for select
  to authenticated
  using (auth.uid() = id);

drop policy if exists "profiles: insert own" on public.profiles;
create policy "profiles: insert own"
  on public.profiles for insert
  to authenticated
  with check (auth.uid() = id);

drop policy if exists "profiles: update own" on public.profiles;
create policy "profiles: update own"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- Keep updated_at honest without the client having to set it.
create or replace function public.touch_profiles_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
  before update on public.profiles
  for each row execute function public.touch_profiles_updated_at();

-- Create the profile row at sign-up from the metadata the form sends.
-- The exception block is deliberate: a profile row that cannot be written must
-- never abort account creation, because the user would then be unable to sign
-- in at all. Failures surface as a warning in the Supabase logs instead.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, age, gender, phone, abha_id)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name',
    nullif(new.raw_user_meta_data ->> 'age', '')::integer,
    new.raw_user_meta_data ->> 'gender',
    new.raw_user_meta_data ->> 'phone',
    new.raw_user_meta_data ->> 'abha_id'
  )
  on conflict (id) do nothing;
  return new;
exception
  when others then
    raise warning 'handle_new_user: could not create profile for %: %', new.id, sqlerrm;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ------------------------------------------------------------- assessments --
-- One row per triage run. vitals/symptoms/triage_result are jsonb so the shape
-- can evolve without a migration each time the form gains a field.
create table if not exists public.assessments (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at    timestamptz not null default now(),
  vitals        jsonb not null default '{}'::jsonb,
  symptoms      jsonb not null default '{}'::jsonb,
  triage_result jsonb not null default '{}'::jsonb
);

alter table public.assessments enable row level security;

drop policy if exists "assessments: read own" on public.assessments;
create policy "assessments: read own"
  on public.assessments for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "assessments: insert own" on public.assessments;
create policy "assessments: insert own"
  on public.assessments for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "assessments: delete own" on public.assessments;
create policy "assessments: delete own"
  on public.assessments for delete
  to authenticated
  using (auth.uid() = user_id);

-- History is always read newest-first for one patient.
create index if not exists assessments_user_created_idx
  on public.assessments (user_id, created_at desc);

