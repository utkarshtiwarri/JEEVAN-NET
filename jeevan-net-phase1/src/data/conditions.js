// This file IS the brain of the Voice Companion. To teach the companion a new
// disease, add one object to the CONDITIONS array below. No UI code changes,
// no new if/else branch. That is the whole point of this file.
//
// How to read a condition entry:
//
//   id           unique slug, lowercase_with_underscores
//   name         English clinical label shown in the assessment banner
//   nameHi       Hindi label (used in spoken output when lang is hi-IN)
//   icd10        ICD-10 code — judges and doctors both look for this
//   specialty    must match a `specialty` in data/doctors.js
//   severity     LOW | MODERATE | HIGH | CRITICAL  (baseline, before triage)
//   emergency    true  -> may trigger ambulance dispatch
//   emergencyAt  score at/above which this condition upgrades to an emergency.
//                Optional; defaults to 4. Lower it for deadlier conditions.
//   keywords     { spoken phrase : weight }. Weights 1-5. Use 3+ only for
//                phrases that are near-diagnostic for this condition.
//   firstAid     Safe, non-prescription steps only. NEVER a drug dose.
//   questions    Follow-up questions the companion asks back.
//   action       What the patient should do next.
//
// SAFETY RULES FOR ANYONE EDITING THIS FILE (non-negotiable):
//   1. Never write a medicine name with a dose. "Take paracetamol 500mg"
//      is a prescription. "You may ask your doctor about fever relief" is not.
//   2. Never write the word "cure". The companion triages and routes; it does
//      not treat.
//   3. If a condition can kill within the hour, set emergency: true.
//   4. A single vague word ("dard", "fever", "weakness") must never be worth
//      more than 1. Those words appear in a dozen conditions.
//   5. `escalateOn` danger signs must be listed in BOTH Romanised and Devanagari
//      forms. The microphone returns Devanagari for lang="hi-IN", so a
//      Romanised-only list silently never escalates: the typed path and the
//      spoken path then disagree about whether the same patient is in danger.
//   6. `emergencyAt` is calibrated against STACKED scores. A phrase and the
//      shorter phrase inside it both match ("बहुत प्यास" and "प्यास"), so a
//      symptom-only utterance reaches 7-8 for conditions whose key phrases
//      overlap. Set the threshold above that unless a bare symptom really is an
//      emergency; run `node scripts/test-voice-engine.mjs` after any change.
// ============================================================================

